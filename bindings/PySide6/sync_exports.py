#!/usr/bin/env python
"""Regenerate the static export lists of the PySide6FluentUI subpackages.

The subpackage ``__init__`` files import every bound class by name instead of
using ``import *`` plus a runtime-computed ``__all__``: type checkers and VSCode
(Pylance/Jedi) cannot evaluate ``dir()`` on a native module, so a dynamic
``__all__`` silently kills code completion for ``from ... import *``.

Source of truth: the ``FLUENTUI_HEADERS`` list in ``bindings/PySide6/CMakeLists.txt``.
Class names match their header file names one-to-one (verified by --check).

Usage:
    python sync_exports.py            # rewrite the subpackage __init__ files
    python sync_exports.py --check    # fail if they are out of date
"""

import argparse
import os
import re
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.normpath(os.path.join(SCRIPT_DIR, "..", ".."))
CMAKE_LISTS = os.path.join(SCRIPT_DIR, "CMakeLists.txt")
PACKAGE_DIR = os.path.join(SCRIPT_DIR, "PySide6FluentUI")

SUBPACKAGES = ("controls", "utils")

TEMPLATE = '''"""{summary}

Generated by ``bindings/PySide6/sync_exports.py`` from the ``FLUENTUI_HEADERS``
list in ``bindings/PySide6/CMakeLists.txt``. Edit that list and rerun the script
instead of hand-maintaining the names below -- explicit imports keep the exports
statically analyzable, which ``import *`` plus a computed ``__all__`` does not.
"""

from ..PySide6FluentUI import (
{imports}
)

__all__ = [
{names}
]
'''


def parse_headers(cmake_text):
    """Return {'controls': [...], 'utils': [...]} class names from the header list."""
    match = re.search(r"set\(FLUENTUI_HEADERS(.*?)\n\)", cmake_text, re.S)
    if not match:
        raise SystemExit("Error: FLUENTUI_HEADERS block not found in CMakeLists.txt")

    groups = {name: [] for name in SUBPACKAGES}
    for rel_path in re.findall(r"\$\{CMAKE_SOURCE_DIR\}/([^\"\s]+\.h)", match.group(1)):
        directory, file_name = rel_path.split("/", 1)
        if directory not in groups:
            continue
        class_name = os.path.splitext(file_name)[0]
        if class_name not in groups[directory]:
            groups[directory].append(class_name)
    return groups


def header_paths(cmake_text):
    match = re.search(r"set\(FLUENTUI_HEADERS(.*?)\n\)", cmake_text, re.S)
    return re.findall(r"\$\{CMAKE_SOURCE_DIR\}/([^\"\s]+\.h)", match.group(1))


def verify_headers_declare_classes(cmake_text):
    """Class name must appear as a class declaration in its own header."""
    problems = []
    for rel_path in header_paths(cmake_text):
        absolute = os.path.join(REPO_ROOT, rel_path.replace("/", os.sep))
        class_name = os.path.splitext(os.path.basename(absolute))[0]
        if not os.path.isfile(absolute):
            problems.append("missing header: {0}".format(rel_path))
            continue
        with open(absolute, encoding="utf-8", errors="replace") as stream:
            body = stream.read()
        if not re.search(r"\bclass\s+(?:\w+\s+)?" + re.escape(class_name) + r"\b", body):
            problems.append("{0}: no `class {1}` declaration".format(rel_path, class_name))
    return problems


def render(subpackage, classes):
    if subpackage == "utils":
        summary = (
            "FluentUI utility helpers re-exported from the native PySide6FluentUI module.\n"
            "\n"
            "Only the helper classes declared under ``utils/`` are exposed here; the\n"
            "control classes live in :mod:`PySide6FluentUI.controls`."
        )
    else:
        summary = (
            "FluentUI control classes re-exported from the native PySide6FluentUI module.\n"
            "\n"
            "Everything bound from ``controls/`` is exposed here; the helper classes\n"
            "bound from ``utils/`` are only reachable through\n"
            ":mod:`PySide6FluentUI.utils`."
        )

    ordered = sorted(classes)
    imports = "\n".join("    {0},".format(name) for name in ordered)
    names = "\n".join('    "{0}",'.format(name) for name in ordered)
    return TEMPLATE.format(summary=summary, imports=imports, names=names)


def target_path(subpackage):
    return os.path.join(PACKAGE_DIR, subpackage, "__init__.py")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="report drift instead of rewriting the files",
    )
    args = parser.parse_args()

    with open(CMAKE_LISTS, encoding="utf-8") as stream:
        cmake_text = stream.read()

    groups = parse_headers(cmake_text)
    for subpackage in SUBPACKAGES:
        if not groups[subpackage]:
            raise SystemExit("Error: no {0} headers found".format(subpackage))

    problems = verify_headers_declare_classes(cmake_text)
    if problems:
        print("Header/class-name mismatches:")
        for problem in problems:
            print("  - {0}".format(problem))
        return 1

    print("controls: {0} classes, utils: {1} classes".format(
        len(groups["controls"]), len(groups["utils"])))

    stale = []
    for subpackage in SUBPACKAGES:
        path = target_path(subpackage)
        content = render(subpackage, groups[subpackage])
        existing = None
        if os.path.isfile(path):
            with open(path, encoding="utf-8") as stream:
                existing = stream.read()
        if existing == content:
            print("up to date: {0}".format(os.path.relpath(path, REPO_ROOT)))
            continue
        stale.append(subpackage)
        if args.check:
            print("OUT OF DATE: {0}".format(os.path.relpath(path, REPO_ROOT)))
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(content)
        print("rewrote: {0}".format(os.path.relpath(path, REPO_ROOT)))

    if args.check and stale:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
